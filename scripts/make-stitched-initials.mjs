// Generates public/journal-3d/stitched-initials.svg: Tammana's initials, "tk", as a line of short
// backstitches along cursive strokes. Every stitch is its own `M x y L x y` segment, because the 3D cover
// (app/diary-cover-scene.ts) turns each one into a raised thread. Run: node scripts/make-stitched-initials.mjs
import { writeFile } from "node:fs/promises";

const width = 120, height = 84, stitch = 4.6, gap = 1.3;

// Each stroke is a start point and cubic curves: [x1, y1, x2, y2, x, y].
const strokes = [
  // t: a stem that curls out at the foot, then its cross.
  { from: [30, 8], curves: [[30, 30, 28.5, 54, 30, 66], [31, 76, 41, 80, 50, 71]] },
  { from: [17, 31], curves: [[26, 29.5, 37, 28.5, 46, 27.5]] },
  // k: a tall stem, a small looped arm, and a leg that kicks out.
  { from: [67, 3], curves: [[67, 28, 65, 54, 63, 79]] },
  { from: [64.5, 55], curves: [[75, 37, 97, 32, 95.5, 44], [94, 54, 79, 56.5, 69, 54.5]] },
  { from: [72, 55.5], curves: [[81, 62, 89, 76, 104, 79]] },
];

const cubic = (p0, [x1, y1, x2, y2, x, y], t) => {
  const u = 1 - t;
  return [u ** 3 * p0[0] + 3 * u * u * t * x1 + 3 * u * t * t * x2 + t ** 3 * x, u ** 3 * p0[1] + 3 * u * u * t * y1 + 3 * u * t * t * y2 + t ** 3 * y];
};

// Walk each stroke by arc length, laying a stitch, leaving a gap, and repeating.
const segments = [];
for (const { from, curves } of strokes) {
  const points = [from];
  let start = from;
  for (const curve of curves) {
    for (let i = 1; i <= 80; i++) points.push(cubic(start, curve, i / 80));
    start = curve.slice(4);
  }
  let travelled = 0, mark = 0, sewing = true, begin = points[0];
  for (let i = 1; i < points.length; i++) {
    const [ax, ay] = points[i - 1], [bx, by] = points[i];
    travelled += Math.hypot(bx - ax, by - ay);
    if (sewing && travelled - mark >= stitch) { segments.push([begin, points[i]]); sewing = false; mark = travelled; }
    else if (!sewing && travelled - mark >= gap) { begin = points[i]; sewing = true; mark = travelled; }
  }
  if (sewing && travelled - mark > stitch * .45) segments.push([begin, points[points.length - 1]]);
}

const f = n => n.toFixed(2).replace(/\.?0+$/, "");
const d = segments.map(([[ax, ay], [bx, by]]) => `M${f(ax)} ${f(ay)}L${f(bx)} ${f(by)}`).join(" ");
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" fill="none" stroke="#f4f0e6" stroke-width="1.7" stroke-linecap="round" role="img" aria-label="tk, Tammana's initials, backstitched in white">
  <title>tk</title>
  <desc>Cursive initials t and k, sewn in white backstitch. Generated by scripts/make-stitched-initials.mjs.</desc>
  <path d="${d}"/>
</svg>
`;
await writeFile(new URL("../public/journal-3d/stitched-initials.svg", import.meta.url), svg);
console.log(`${segments.length} stitches`);
