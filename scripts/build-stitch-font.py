alphabet['’'] = alphabet["'"]
alphabet['‘'] = alphabet["'"]
alphabet['–'] = alphabet['-']
alphabet['—'] = alphabet['-']
alphabet[' '] = ['000'] * 7

glyphs, metrics, cmap = {}, {}, {}

def draw_glyph(pattern):
    pen = TTGlyphPen(None)
    for row, line in enumerate(pattern):
        for column, filled in enumerate(line):
            if filled != '1':
                continue
            x, y = 35 + column * 100, 650 - row * 100
            # One closed X contour avoids overlapping strokes in rasterizers.
            contour = [(0,24),(24,0),(44,20),(64,0),(88,24),(68,44),
                       (88,64),(64,88),(44,68),(24,88),(0,64),(20,44)]
            pen.moveTo((x + contour[0][0], y + contour[0][1]))
            for px, py in contour[1:]:
                pen.lineTo((x + px, y + py))
            pen.closePath()
    return pen.glyph()

glyphs['.notdef'] = draw_glyph(alphabet['?'])
metrics['.notdef'] = (600, 35)
for character, pattern in alphabet.items():
    name = f'uni{ord(character):04X}'
    glyphs[name] = draw_glyph(pattern)
    metrics[name] = (len(pattern[0]) * 100 + 80, 35)
    cmap[ord(character)] = name

font = FontBuilder(1000, isTTF=True)
font.setupGlyphOrder(list(glyphs))
font.setupCharacterMap(cmap)
font.setupGlyf(glyphs)
font.setupHorizontalMetrics(metrics)
font.setupHorizontalHeader(ascent=850, descent=-150)
font.setupNameTable({'familyName': 'Little Red Stitches', 'styleName': 'Regular',
                    'uniqueFontIdentifier': 'LittleRedStitches-1.0',
                    'fullName': 'Little Red Stitches', 'psName': 'LittleRedStitches-Regular',
                    'version': 'Version 1.0'})
font.setupOS2(sTypoAscender=850, sTypoDescender=-150, usWinAscent=850, usWinDescent=150)
font.setupPost()
font.setupMaxp()
root = Path(__file__).resolve().parent.parent
target = root / 'public/fonts/little-red-stitches.ttf'
target.parent.mkdir(parents=True, exist_ok=True)
font.save(target)
static = root / 'static/fonts'
static.mkdir(parents=True, exist_ok=True)
shutil.copyfile(target, static / target.name)
print(f'Built {len(cmap)} cross-stitch characters: {target.name}')
