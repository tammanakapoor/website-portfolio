// Builds the GitHub Pages copy of the site in static/ from the real app.
// Each page is rendered by the production worker build, then served as plain files next to the
// build's own browser assets, so tammanakapoor.github.io shows exactly what Cloudflare shows.
//
//   node scripts/build-static-site.mjs               build the app, then regenerate static/
//   node scripts/build-static-site.mjs --skip-build  reuse the existing dist/ build
//   node scripts/build-static-site.mjs --out=<dir>   write somewhere other than static/
import { build } from 'esbuild';
import { execSync } from 'node:child_process';
import { cp, mkdir, rm, writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import path from 'node:path';

const site = 'https://tammanakapoor.github.io';
const root = path.resolve(import.meta.dirname, '..');
const outArg = process.argv.find(arg => arg.startsWith('--out='));
const out = path.resolve(root, outArg ? outArg.slice(6) : 'static');
// Cloudflare-only build files, and files in public/ that only the retired typewriter and oval homes used.
const unused = new Set(['_headers', '.assetsignore', '.vite', 'media', 'oval-home.js', 'typewriter-scene.js', 'whimsy-home.js']);

if (!process.argv.includes('--skip-build')) execSync('npx vinext build', { cwd: root, stdio: 'inherit' });

// Project ids come from the same data the site uses.
const cache = path.join(root, '.wrangler/static-site');
await mkdir(cache, { recursive: true });
await build({ entryPoints: [path.join(root, 'app/projects/data.ts')], outfile: path.join(cache, 'data.mjs'), bundle: true, platform: 'node', format: 'esm', logLevel: 'warning' });
const { projects } = await import(pathToFileURL(path.join(cache, 'data.mjs')).href + `?t=${Date.now()}`);

const { default: worker } = await import(pathToFileURL(path.join(root, 'dist/server/index.js')).href);
const env = { ASSETS: { fetch: async () => new Response('Not found', { status: 404 }) }, IMAGES: {} };
async function render(route, expected = 200) {
  const response = await worker.fetch(new Request(site + route), env, { waitUntil() {}, passThroughOnException() {} });
  if (response.status !== expected) throw new Error(`${route} rendered with status ${response.status}`);
  return response.text();
}

// A small page that forwards an old address to where that content lives now.
function forward(target) {
  return `<!DOCTYPE html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n<title>Tammana Kapoor</title>\n<meta http-equiv="refresh" content="0; url=${target}">\n<link rel="canonical" href="${site}${target}">\n<script>location.replace(${JSON.stringify(target)})</script>\n</head>\n<body><a href="${target}">Continue to Tammana’s journal</a></body>\n</html>\n`;
}

await rm(out, { recursive: true, force: true });
await cp(path.join(root, 'dist/client'), out, { recursive: true, filter: source => !unused.has(path.relative(path.join(root, 'dist/client'), source)) });

const pages = { 'index.html': await render('/'), '404.html': await render('/this-page-does-not-exist', 404) };
for (const project of projects) pages[`projects/${project.id}.html`] = await render(`/projects/${project.id}`);
// Addresses from the earlier plain HTML site keep working.
pages['projects.html'] = forward('/#projects');
for (const project of projects) pages[`${project.id}.html`] = forward(`/projects/${project.id}`);
pages['outside.html'] = forward('/#outside');
pages['lab.html'] = forward('/');

await mkdir(path.join(out, 'projects'), { recursive: true });
for (const [file, html] of Object.entries(pages)) await writeFile(path.join(out, file), html);
// GitHub Pages runs Jekyll by default, which drops folders starting with "_" such as assets/_vinext_fonts.
await writeFile(path.join(out, '.nojekyll'), '');
await writeFile(path.join(out, 'README.md'), `# GitHub Pages copy of the site

Generated by \`node scripts/build-static-site.mjs\`. Do not edit these files: change the app in \`app/\` and \`public/\`, then run the script again.

Every page is rendered by the production build of the app and served with the build's own browser assets, so ${site} matches the Cloudflare site exactly, including the 3D cover, page turning and the projects folder.

| Address | File |
| --- | --- |
| \`/\` | \`index.html\`, the journal |
| \`/projects/<id>\` | \`projects/<id>.html\`, one per project |
| \`/projects\`, \`/outside\`, \`/lab\`, \`/daily-cafe\` and the other old project addresses | Small pages that forward to the journal or the new project pages |

\`.nojekyll\` stops GitHub Pages running Jekyll, which would otherwise drop \`assets/_vinext_fonts\`.
`);
console.log(`Static site written to ${path.relative(root, out)}/: ${Object.keys(pages).length} pages.`);
